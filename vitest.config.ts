// vitest 自报 ~12 秒、含启动的墙钟 14–20 秒；此前写"约 6–9 秒"），完全够快；
// ⚠️ 这里**不写具体例数** —— 与「完成标准」那条同源：N 会随用例增删漂移，
// 而它已经漂过一次（写下时 277，补了四条后是 281，没人回头改；2026-10-08 又涨到
